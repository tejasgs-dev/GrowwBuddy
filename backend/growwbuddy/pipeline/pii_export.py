"""Export the PII guard's regexes as JSON for the web UI's pre-check (task 5.8, EV-5-07).

    python -m growwbuddy.pipeline.pii_export          # write the file
    python -m growwbuddy.pipeline.pii_export --check  # exit 1 if the file is out of date

The UI's check is a courtesy warning only; the server guard (`pii_guard.check`) decides.
The UI re-implements the small amount of logic around the patterns (Verhoeff, the amount
exception, the OTP keyword window), so only the patterns themselves are shared.

Every pattern here uses syntax that means the same in Python `re` and JavaScript
`RegExp` (lookbehind, `\\d`, `\\w`, `\\s`, `\\b`); the UI test compiles each one.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from growwbuddy.config import PROJECT_ROOT
from growwbuddy.pipeline import pii_guard as g

OUTPUT_PATH: Path = PROJECT_ROOT / "frontend" / "src" / "generated" / "pii-patterns.json"

_PATTERNS: dict[str, re.Pattern[str]] = {
    "pan": g._PAN,
    "pan_spaced": g._PAN_SPACED,
    "aadhaar": g._AADHAAR,
    "phone": g._PHONE,
    "email": g._EMAIL,
    "email_disguised": g._EMAIL_DISGUISED,
    "amount_before": g._AMOUNT_BEFORE,
    "amount_after": g._AMOUNT_AFTER,
    "otp_word": g._OTP_WORD,
    "short_number": g._SHORT_NUMBER,
    "account": g._ACCOUNT,
}


def _flags(p: re.Pattern[str]) -> str:
    return "i" if p.flags & re.IGNORECASE else ""


def export() -> str:
    """The JSON text, stable across runs (sorted keys, trailing newline)."""
    data = {
        "_comment": (
            "Generated by `python -m growwbuddy.pipeline.pii_export` from "
            "backend/growwbuddy/pipeline/pii_guard.py. Do not edit by hand."
        ),
        "near": g._NEAR,
        "patterns": {
            name: {"source": p.pattern, "flags": _flags(p)} for name, p in _PATTERNS.items()
        },
    }
    return json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args(argv)
    text = export()
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != text:
            print(f"{OUTPUT_PATH} is out of date; run `make pii-patterns`", file=sys.stderr)
            return 1
        print("PII patterns in sync")
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
